export interface LunarDate {
  year: number;
  month: number;
  day: number;
  isLeap: boolean;
}

// Convert solar date to lunar date (approximation for 1900-2030)
export function solarToLunar(year: number, month: number, day: number): LunarDate {
  const newYear = LUNAR_NEW_YEAR[year];
  if (!newYear) {
    // Fallback for years outside range
    return { year, month, day, isLeap: false };
  }

  const solarDate = new Date(year, month - 1, day);
  const lunarStart = new Date(year, newYear.m - 1, newYear.d);

  // If before lunar new year, it's previous lunar year
  if (solarDate < lunarStart) {
    const prevYear = year - 1;
    const prevNewYear = LUNAR_NEW_YEAR[prevYear];
    if (!prevNewYear) return { year: prevYear, month, day, isLeap: false };
    const prevStart = new Date(prevYear, prevNewYear.m - 1, prevNewYear.d);
    const daysSince = Math.floor((solarDate.getTime() - prevStart.getTime()) / 86400000);
    const monthDays = LUNAR_MONTH_DAYS[prevYear] || [30, 29, 30, 29, 30, 29, 30, 29, 30, 29, 30, 29];
    let lunarMonth = 1;
    let lunarDay = daysSince + 1;
    for (let i = 0; i < 12; i++) {
      if (lunarDay <= monthDays[i]) break;
      lunarDay -= monthDays[i];
      lunarMonth++;
    }
    return { year: prevYear, month: lunarMonth, day: lunarDay, isLeap: false };
  }

  // After lunar new year
  const daysSince = Math.floor((solarDate.getTime() - lunarStart.getTime()) / 86400000);
  const monthDays = LUNAR_MONTH_DAYS[year] || [30, 29, 30, 29, 30, 29, 30, 29, 30, 29, 30, 29];
  let lunarMonth = 1;
  let lunarDay = daysSince + 1;
  for (let i = 0; i < 12; i++) {
    if (lunarDay <= monthDays[i]) break;
    lunarDay -= monthDays[i];
    lunarMonth++;
  }
  return { year, month: lunarMonth, day: lunarDay, isLeap: false };
}
